#!/usr/bin/env python3
"""Capture this branch's machine, including opt-in runtime references; never install them."""
import argparse
from datetime import datetime, timezone
import hashlib
import json
from pathlib import Path
import shutil
import socket
import subprocess

ROOT = Path(__file__).resolve().parents[1]


def capture(apply=False):
    machine = json.loads((ROOT / 'hardware/machine.json').read_text())
    branch = subprocess.check_output(['git', '-C', str(ROOT), 'branch', '--show-current'], text=True).strip()
    if branch != machine['branch'] or socket.gethostname() != machine['hostname']:
        raise SystemExit('Machine or branch mismatch; inspect hardware/machine.json before capturing.')
    source = Path.home() / '.local/share/clavis-source'
    source_branch = subprocess.check_output(['git', '-C', str(source), 'branch', '--show-current'], text=True).strip()
    if source_branch != branch:
        raise SystemExit('Clavis and desktop-config must use the same machine branch.')
    print(f"Capture {machine['id']} from {machine['hostname']} on {branch}")
    if not apply:
        print('Preview only. Use --apply to update the repository snapshot; no live configuration is changed.')
        return
    subprocess.run(['python3', str(ROOT / 'scripts/capture-current.py'), '--apply'], check=True)
    home = Path.home()
    destination = ROOT / 'system-reference/machine'
    # This subtree is exclusively generated by this command. Remove stale
    # machine references without touching shared source references elsewhere.
    if destination.exists():
        shutil.rmtree(destination)
    destination.mkdir(parents=True)
    files = set()
    for directory, pattern in [
        (home / '.config/niri', '*.kdl'),
        (home / '.config/systemd/user/niri.service.d', '*.conf'),
        (home / '.config/systemd/user/clavis-shell.service.d', '*.conf'),
        (Path('/etc/systemd/sleep.conf.d'), '*.conf'),
        (Path('/etc/modprobe.d'), '*nvidia*.conf'),
        (Path('/etc/systemd/system/nvidia-suspend.service.d'), '*.conf'),
        (Path('/etc/systemd/system/nvidia-resume.service.d'), '*.conf'),
        (Path('/etc/systemd/system/nvidia-hibernate.service.d'), '*.conf'),
    ]:
        files.update(p for p in directory.glob(pattern) if p.is_file())
    for p in [Path('/etc/systemd/sleep.conf'), Path('/etc/systemd/logind.conf')]:
        if p.is_file():
            files.add(p)
    inventory = []
    for source_file in sorted(files):
        relative = (Path('user-home') / source_file.relative_to(home)
                    if source_file.is_relative_to(home)
                    else Path('system') / source_file.relative_to('/'))
        target = destination / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(source_file.read_text().replace(str(home), '@HOME@'))
        inventory.append(str(relative))
    pid = subprocess.check_output(['systemctl', '--user', 'show', 'niri.service', '-p', 'MainPID', '--value'], text=True).strip()
    executable = Path('/proc') / pid / 'exe'
    runtime = {
        'captured_at_utc': datetime.now(timezone.utc).isoformat(timespec='seconds'),
        'machine': machine['id'],
        'reference_only': True,
        'files': inventory,
        'niri': {'executable': str(executable.resolve()).replace(str(home), '@HOME@')},
    }
    if executable.is_file():
        with executable.open('rb') as stream:
            runtime['niri']['sha256'] = hashlib.file_digest(stream, 'sha256').hexdigest()
        runtime['niri']['version'] = subprocess.check_output([str(executable), '--version'], text=True).strip()
    (destination / 'inventory.json').write_text(json.dumps(runtime, ensure_ascii=False, indent=2) + '\n')
    subprocess.run(['python3', str(ROOT / 'scripts/update-manifest.py')], check=True)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--apply', action='store_true')
    capture(parser.parse_args().apply)
